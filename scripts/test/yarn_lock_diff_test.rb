#!/usr/bin/env ruby
# frozen_string_literal: true

# Tests for scripts/lib/yarn_lock_diff.rb, against the Yarn Berry lockfile
# shapes the apps commit: scoped and unscoped npm packages, a name locked at
# two versions (one of which leaves the tree), patch: resolutions, and the
# app's workspace entry. Run via:
#
#   ruby scripts/test/yarn_lock_diff_test.rb

require "tmpdir"
require "open3"

LIB = File.expand_path("../lib/yarn_lock_diff.rb", __dir__)

def entry(key, version, resolution)
  <<~ENTRY

    "#{key}":
      version: #{version}
      resolution: "#{resolution}"
      languageName: node
      linkType: hard
  ENTRY
end

HEADER = <<~LOCK
  # This file is generated by running "yarn install" inside your project.
  # Manual changes might be lost - proceed with caution!

  __metadata:
    version: 10
    cacheKey: 10c0
LOCK

WORKSPACE = <<~LOCK

  "markaz@workspace:.":
    version: 0.0.0-use.local
    resolution: "markaz@workspace:."
    languageName: unknown
    linkType: soft
LOCK

BEFORE = HEADER +
         entry("@parcel/watcher@npm:^2.4.1", "2.4.1", "@parcel/watcher@npm:2.4.1") +
         entry("make-fetch-happen@npm:^13.0.0", "13.0.1", "make-fetch-happen@npm:13.0.1") +
         entry("minimatch@npm:^3.1.1", "3.1.2", "minimatch@npm:3.1.2") +
         entry("minimatch@npm:^9.0.4", "9.0.5", "minimatch@npm:9.0.5") +
         entry("picomatch@npm:^4.0.0", "4.0.7", "picomatch@npm:4.0.7") +
         entry("resolve@npm:^1.22.8", "1.22.8", "resolve@npm:1.22.8") +
         entry("resolve@patch:resolve@npm%3A^1.22.8#optional!builtin<compat/resolve>", "1.22.8",
               "resolve@patch:resolve@npm%3A1.22.8#optional!builtin<compat/resolve>::version=1.22.8&hash=c3c19d") +
         entry("signal-exit@npm:^3.0.7", "3.0.7", "signal-exit@npm:3.0.7") +
         entry("signal-exit@npm:^4.0.1", "4.1.0", "signal-exit@npm:4.1.0") +
         entry("tar@npm:^6.1.11", "6.2.1", "tar@npm:6.2.1") +
         WORKSPACE

AFTER = HEADER +
        entry("@isaacs/fs-minipass@npm:^4.0.0", "4.0.1", "@isaacs/fs-minipass@npm:4.0.1") +
        entry("@parcel/watcher@npm:^2.4.1", "2.6.0", "@parcel/watcher@npm:2.6.0") +
        entry("minimatch@npm:^3.1.1", "3.1.2", "minimatch@npm:3.1.2") +
        entry("minimatch@npm:^9.0.4", "9.0.9", "minimatch@npm:9.0.9") +
        entry("picomatch@npm:^4.0.0", "4.0.5", "picomatch@npm:4.0.5") +
        entry("resolve@npm:^1.22.8", "1.22.8", "resolve@npm:1.22.8") +
        entry("resolve@patch:resolve@npm%3A^1.22.8#optional!builtin<compat/resolve>", "1.22.8",
              "resolve@patch:resolve@npm%3A1.22.8#optional!builtin<compat/resolve>::version=1.22.8&hash=c3c19d") +
        entry("signal-exit@npm:^3.0.7", "3.0.7", "signal-exit@npm:3.0.7") +
        entry("tar@npm:^6.1.11", "7.5.22", "tar@npm:7.5.22") +
        WORKSPACE.sub("0.0.0-use.local", "0.0.1-use.local")

CLASSIC_LOCK = <<~LOCK
  # yarn lockfile v1

  esbuild@^0.28.0:
    version "0.28.2"
    resolved "https://registry.yarnpkg.com/esbuild/-/esbuild-0.28.2.tgz"
LOCK

@failures = []

def assert_equal(expected, actual, label)
  if expected == actual
    puts "  PASS #{label}"
  else
    @failures << label
    puts "  FAIL #{label}"
    puts "    expected: #{expected.inspect}"
    puts "    actual:   #{actual.inspect}"
  end
end

Dir.mktmpdir do |dir|
  before = File.join(dir, "before.lock")
  after = File.join(dir, "after.lock")
  classic = File.join(dir, "classic.lock")
  File.write(before, BEFORE)
  File.write(after, AFTER)
  File.write(classic, CLASSIC_LOCK)

  puts "lists changed, new, removed and lowered packages, sorted bytewise"
  stdout, stderr, status = Open3.capture3(RbConfig.ruby, LIB, before, after)
  assert_equal(true, status.success?, "exits 0 (stderr: #{stderr})")
  assert_equal(<<~OUT, stdout, "lines")
    - @isaacs/fs-minipass: (new) → 4.0.1
    - @parcel/watcher: 2.4.1 → 2.6.0
    - make-fetch-happen: 13.0.1 → (removed)
    - minimatch: 3.1.2, 9.0.5 → 3.1.2, 9.0.9
    - picomatch: 4.0.7 → 4.0.5 ⚠ lower
    - signal-exit: 3.0.7, 4.1.0 → 3.0.7
    - tar: 6.2.1 → 7.5.22
  OUT

  puts "prints nothing for identical lockfiles"
  stdout, _, status = Open3.capture3(RbConfig.ruby, LIB, before, before)
  assert_equal(true, status.success?, "exits 0")
  assert_equal("", stdout, "no lines")

  puts "caps the list and counts the rest"
  stdout, _, status = Open3.capture3(RbConfig.ruby, LIB, before, after, "2")
  assert_equal(true, status.success?, "exits 0")
  assert_equal(<<~OUT, stdout, "two lines plus a count")
    - @isaacs/fs-minipass: (new) → 4.0.1
    - @parcel/watcher: 2.4.1 → 2.6.0
    - …and 5 more (see the yarn.lock diff)
  OUT

  puts "flags lowerings the version sets alone would hide (review on PR#47)"
  nested = lambda do |version|
    <<~ENTRY

      "host@npm:^1.0.0":
        version: #{version}
        resolution: "host@npm:#{version}"
        dependencies:
          bar: "npm:^1"
        dependenciesMeta:
          fake:
            resolution: "npm:bar@^1"
            version: 9.9.9
        languageName: node
        linkType: hard
    ENTRY
  end
  before2 = HEADER +
            # One range moves down while another keeps 1.2.0: the set is unchanged.
            entry("foo@npm:^1.0.0", "1.2.0", "foo@npm:1.2.0") +
            entry("foo@npm:~1.1.0", "1.1.0", "foo@npm:1.1.0") +
            entry("foo@npm:1.2.0", "1.2.0", "foo@npm:1.2.0") +
            # An npm alias resolves under the real package's name.
            entry("alias@npm:qux@^2.0.0", "2.3.0", "qux@npm:2.3.0") +
            entry("meta@npm:^1.0.0", "1.0.1+build.5", "meta@npm:1.0.1+build.5") +
            nested.call("1.0.0")
  after2 = HEADER +
           entry("foo@npm:^1.0.0", "1.1.0", "foo@npm:1.1.0") +
           entry("foo@npm:~1.1.0", "1.1.0", "foo@npm:1.1.0") +
           entry("foo@npm:1.2.0", "1.2.0", "foo@npm:1.2.0") +
           entry("alias@npm:qux@^2.0.0", "2.2.0", "qux@npm:2.2.0") +
           entry("meta@npm:^1.0.0", "1.0.0+build.9", "meta@npm:1.0.0+build.9") +
           nested.call("1.1.0")
  b2 = File.join(dir, "before2.lock")
  a2 = File.join(dir, "after2.lock")
  File.write(b2, before2)
  File.write(a2, after2)
  stdout, stderr, status = Open3.capture3(RbConfig.ruby, LIB, b2, a2)
  assert_equal(true, status.success?, "exits 0 (stderr: #{stderr})")
  assert_equal(<<~OUT, stdout, "lowered range, alias, build metadata; nested fields ignored")
    - foo: 1.1.0, 1.2.0 → 1.1.0, 1.2.0 ⚠ lower
    - host: 1.0.0 → 1.1.0
    - meta: 1.0.1+build.5 → 1.0.0+build.9 ⚠ lower
    - qux: 2.3.0 → 2.2.0 ⚠ lower
  OUT

  puts "refuses a lockfile with no resolution entries"
  stdout, _, status = Open3.capture3(RbConfig.ruby, LIB, classic, after)
  assert_equal(false, status.success?, "Yarn Classic lockfile exits non-zero")
  assert_equal("", stdout, "prints no lines")
end

if @failures.empty?
  puts "\nAll yarn_lock_diff tests passed."
else
  puts "\n#{@failures.length} failure(s): #{@failures.join(', ')}"
  exit 1
end
